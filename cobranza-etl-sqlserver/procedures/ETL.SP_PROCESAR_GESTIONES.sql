/* ============================================================================
   ETL.SP_PROCESAR_GESTIONES
   Carga INCREMENTAL e IDEMPOTENTE de gestiones por rango de fechas.
   Ejecutar EN la base BD_MCOB_REPORTING.

   Origen : BD_MCOB (CALL / CARGA / CONFIGURACION / ADMINISTRACION) + BD_MSEG
   Destino: REPORTE.TBL_GESTIONES (acumulativa)

   Parámetros (rango semiabierto [@FECHA_INICIO, @FECHA_FIN)):
     @FECHA_INICIO  DATE  inclusivo. NULL -> AYER (la carga diaria es del día anterior).
     @FECHA_FIN     DATE  exclusivo. NULL -> @FECHA_INICIO + 1 día.

   Estrategia:
     1) TRUNCATE STG + INSERT desde el origen (consulta pesada, fuera de TX).
     2) Transacción corta: DELETE del rango en REPORTE + INSERT desde STG.
        => re-ejecutar el mismo día deja el mismo resultado (idempotente).

   Notas:
     - Filtros SARGABLES por FEC_GEST_DT (sin YEAR()/MONTH()).
     - El DEDUP de CALL.TBL_GESTION_VARIOS lo hacen los procesos WOLKVOX e
       IPBUSINESS antes de este ETL; aquí NO se deduplica el origen.
     - No cambia ninguna regla de negocio respecto del script original.
============================================================================ */
USE BD_MCOB_REPORTING;
GO

CREATE OR ALTER PROCEDURE ETL.SP_PROCESAR_GESTIONES
    @FECHA_INICIO DATE = NULL,
    @FECHA_FIN    DATE = NULL
AS
BEGIN
    SET NOCOUNT ON;
    SET XACT_ABORT ON;

    /* ---- Defaults de rango: por defecto, el día de AYER (completo y ya
            deduplicado por Wolkvox/IPBusiness) ---- */
    IF @FECHA_INICIO IS NULL
        SET @FECHA_INICIO = DATEADD(DAY, -1, CAST(GETDATE() AS DATE));
    IF @FECHA_FIN IS NULL
        SET @FECHA_FIN = DATEADD(DAY, 1, @FECHA_INICIO);

    DECLARE @PROC        VARCHAR(100) = 'SP_PROCESAR_GESTIONES',
            @ID_LOG      BIGINT,
            @FILAS_STG   BIGINT = 0,
            @FILAS_DEL   BIGINT = 0,
            @FILAS_INS   BIGINT = 0,
            @INI_DT      DATETIME2(0) = SYSDATETIME();

    /* ---- Log: inicio ---- */
    INSERT INTO ETL.TBL_PROCESO_LOG
        (NOMBRE_PROCESO, FECHA_INICIO_RANGO, FECHA_FIN_RANGO, ESTADO)
    VALUES
        (@PROC, @FECHA_INICIO, @FECHA_FIN, 'EN_PROCESO');
    SET @ID_LOG = SCOPE_IDENTITY();

    BEGIN TRY
        IF @FECHA_FIN <= @FECHA_INICIO
            THROW 50001, 'El rango es inválido: @FECHA_FIN debe ser mayor que @FECHA_INICIO.', 1;

        /* ===================================================================
           PASO 1 — Aterrizar el rango en STAGING (fuera de transacción)
           =================================================================== */
        TRUNCATE TABLE STG.TBL_GESTIONES_STG;

        INSERT INTO STG.TBL_GESTIONES_STG
        SELECT GES.TIPO AS CODIGO_TIPO,
        CASE GES.TIPO
            WHEN 1 THEN 'GESTIONES'
            ELSE 'CARGAS' END AS DES_TIP_VC,
        CASE GES.ID_CAN_LLA_SI
            WHEN 1 THEN 'GESTIÓN MANUAL'
            ELSE 'PREDICTIVO' END AS DES_TIP_DET_VC,
        GES.ID_GEST_CALL_BI AS CODIGO,
        GES.ID_CONF_BI AS ID_CONFIGURACION,
        CONF.DES_CON_VC AS NOMBRE_CONFIGURACION,
        CLI.NRO_DOC_VC AS DOCUMENTO,
        CLI.NOM_COMP_VC AS NOMBRE_COMPLETO,
        CUE.NRO_CTA_VC AS NUMERO_CUENTA,
        CDA.DES_PROD_VC,
        CDA.DES_GRUP_VC,
        CDA.DES_SEGM_VC,
        CDA.DES_ESTR_VC,
        PRO.NOM_PROV_VC AS PROVEEDOR,
        CAR.NOM_CART_VC AS CARTERA,
        SCA.NOM_SUB_CART_VC AS SUBCARTERA,
        CONVERT(DATE,GES.FEC_GEST_DT) AS FECHA_GESTION,
        CONVERT(TIME, GES.FEC_GEST_DT) HORA_GESTION,
        CASE WHEN GES.TIPO=1 THEN TEL.DES_TEL_VC ELSE ISNULL(TEL.DES_TEL_VC,GES.DES_TEL_VC) END AS TELEFONO,
        TGE.DES_TIP_GES_VC AS TIPO_GESTION,
        CASE
            CASE WHEN TSO.ID_TIP_RES_SI>0 THEN TSO.CAL_TIP_RES_SI
            ELSE TRE.CAL_TIP_RES_SI END
        WHEN 1 THEN 'CONTACTO DIRECTO'
        WHEN 2 THEN 'CONTACTO INDIRECTO'
        WHEN 3 THEN 'NO CONTACTO' END AS TIPO_CONTACTO,
        TRE.DES_TIP_RES_VC AS TIPO_RESULTADO,
        TSO.DES_TIP_RES_VC AS TIPO_SOLUCION,
        CONVERT(DATE,GES.FEC_AGE_CITA_DT) AS FECHA_CITA,
        CONVERT(TIME,GES.FEC_AGE_CITA_DT) AS HORA_CITA,
        CONVERT(DATE,GES.FEC_RE_LLAM_DT) AS FECHA_RELLAMADA,
        CONVERT(TIME,GES.FEC_RE_LLAM_DT) AS HORA_RELLAMADA,
        CONVERT(TIME,GES.HOR_UBI_VC, 100) AS HORARIO_UBICACION,
        ISNULL(GES.MTO_CANC_DO,0) AS MONTO_CANCELACION,
        CONVERT(DATE,GES.FEC_CANC_DT) AS FECHA_CANCELACION,
        GES.NRO_AGENC_VC AS NUMERO_AGENCIA,
        CONVERT(DATE,GES.FEC_COMPR_DT) AS FECHA_COMPROMISO,
        ISNULL(GES.IMP_COMPR_DO,0) AS IMPORTE_COMPROMISO,
        CONVERT(DATE,GES.FEC_OPOR_DT) AS FECHA_OPORTUNIDAD,
        ISNULL(GES.IMP_OPOR_DO,0) AS IMPORTE_OPORTUNIDAD,
        ISNULL(GES.VAL_CUOT_INI_DO,0) AS VALOR_CUOTA_INICIAL,
        CONVERT(DATE,GES.FEC_CUOT_INI_DT) AS FECHA_CUOTA_INICIAL,
        ISNULL(GES.VAL_CUOT_MEN_DO,0) AS VALOR_CUOTA_MENSUAL,
        ISNULL(GES.NRO_CUOT_SI,0) AS NUMERO_CUOTAS,
        GES.TEX_OBS_VC AS OBSERVACION,
        ISNULL(GES.MON_CAPI_DO,0) AS MONTO_CAPITAL,
        ISNULL(GES.MON_DEUD_TOT_DO,0) AS MONTO_DEUDA_TOTAL,
        CASE WHEN GES.TIPO=1 THEN UAS.LOG_USU_VC ELSE GES.ASE_CALL_VC END AS ASESOR_ASIGNADO,
        CASE WHEN GES.TIPO=1 THEN UGE.LOG_USU_VC ELSE GES.ASE_CALL_VC END AS ASESOR_GESTIONA,
        USUP.LOG_USU_VC AS SUPERVISOR_ASIGNADO,
        STA.DES_STA_CLI_VC AS STATUS,
        CON.DESC_COND_VC AS CONDICION,
        CASE WHEN CLI.FLG_RET_PRO_BO=0 THEN 'ACTIVO' ELSE 'RETIRADO' END AS ESTADO_CLIENTE,
        CASE WHEN TSO.ID_TIP_RES_SI>0 THEN TSO.PES_TIP_RES_SI ELSE TRE.PES_TIP_RES_SI END AS PESO_RESULTADO
        FROM (
            SELECT 1 AS TIPO, TX.ID_GEST_CALL_BI, GCC.ID_CTA_BI,
            TX.ID_TIP_GES_SI,TX.FEC_GEST_DT,TX.FEC_AGE_CITA_DT,TX.HOR_AGE_CITA_VC,
            TX.FEC_RE_LLAM_DT,TX.HOR_RE_LLAM_VC,TX.HOR_UBI_VC,
            TX.MTO_CANC_DO,TX.FEC_CANC_DT,TX.NRO_AGENC_VC,TX.FEC_COMPR_DT,TX.IMP_COMPR_DO,
            TX.FEC_OPOR_DT,TX.IMP_OPOR_DO,TX.VAL_CUOT_INI_DO,TX.FEC_CUOT_INI_DT,
            TX.VAL_CUOT_MEN_DO,TX.NRO_CUOT_SI,TX.TEX_OBS_VC,'' AS DES_TEL_VC,
            TX.ID_TEL_BI,TX.ID_CLIE_BI,TX.ID_TIP_RES_SI,TX.ID_TIP_SOL_SI,NULL AS ASE_CALL_VC,
            TX.ID_ASE_CALL_BI,TX.ID_ASE_ASI_SI,TX.ID_SUPER_ASI_SI,
            GCC.MON_CAPI_DO,GCC.MON_DEUD_TOT_DO,
            GCC.ID_SUB_CART_SI,ISNULL(TX.ID_CAN_LLA_SI,1) AS ID_CAN_LLA_SI,
            TX.ID_CONF_BI
            FROM BD_MCOB.CALL.TBL_GESTION_CALL TX
            LEFT JOIN BD_MCOB.CALL.TBL_GESTION_CALL_CUENTAS GCC ON GCC.ID_GEST_CALL_BI=TX.ID_GEST_CALL_BI
            WHERE TX.FLG_EST_BO=1
              AND TX.FEC_GEST_DT >= @FECHA_INICIO
              AND TX.FEC_GEST_DT <  @FECHA_FIN
        ) GES
        LEFT JOIN BD_MCOB.CARGA.TBL_TELEFONO TEL ON TEL.ID_TEL_BI=GES.ID_TEL_BI
        INNER JOIN BD_MCOB.CARGA.TBL_CLIENTE CLI ON CLI.ID_CLIE_BI=GES.ID_CLIE_BI
        LEFT JOIN BD_MCOB.CARGA.TBL_CLIENTE_DATOS_ADICIONALES CLDA ON CLDA.NRO_DOC_VC=CLI.NRO_DOC_VC
        LEFT JOIN BD_MCOB.CARGA.TRF_TIPO_CONDICION CON ON CON.ID_TIP_CON_SI=CLDA.ID_TIP_CON_SI
        LEFT JOIN BD_MCOB.CARGA.TRF_STATUS_CLIENTE STA ON STA.ID_STA_CLI_SI=CLI.ID_STA_CLI_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_CUENTA CUE ON CUE.ID_CTA_BI=GES.ID_CTA_BI
        LEFT JOIN BD_MCOB.CARGA.TBL_CUENTA_DATOS_ADICIONALES CDA ON CDA.ID_CTA_BI=CUE.ID_CTA_BI
        INNER JOIN BD_MCOB.CALL.TBL_TIPO_GESTION TGE ON TGE.ID_TIP_GES_SI=GES.ID_TIP_GES_SI
        INNER JOIN BD_MCOB.CALL.TBL_TIPO_RESULTADO TRE ON TRE.ID_TIP_RES_SI=GES.ID_TIP_RES_SI
        LEFT JOIN BD_MCOB.CALL.TBL_TIPO_RESULTADO TSO ON TSO.ID_TIP_RES_SI=GES.ID_TIP_SOL_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_SUB_CARTERA SCA ON SCA.ID_SUB_CART_SI=GES.ID_SUB_CART_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_CARTERA CAR ON CAR.ID_CART_SI=SCA.ID_CART_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_PROVEEDOR PRO ON PRO.ID_PROV_SI=CAR.ID_PROV_SI
        LEFT JOIN BD_MSEG.DBO.TBL_USUARIO UAS ON UAS.ID_USU_IN=GES.ID_ASE_ASI_SI
        LEFT JOIN BD_MSEG.DBO.TBL_USUARIO UGE ON UGE.ID_USU_IN=GES.ID_ASE_CALL_BI
        LEFT JOIN BD_MCOB.ADMINISTRACION.TBL_ASIG_CART_SUPERV ASI ON ASI.ID_SUB_CART_BI=GES.ID_SUB_CART_SI
            AND ASI.FLG_EST_BO=1
            AND ASI.FLG_ACT_BO=1
        LEFT JOIN BD_MSEG.DBO.TBL_USUARIO USUP ON USUP.ID_USU_IN=ASI.ID_SUPER_SI
        LEFT JOIN BD_MCOB.CONFIGURACION.TBL_CONFIGURACION CONF ON CONF.ID_CONF_BI=GES.ID_CONF_BI
        UNION ALL
        SELECT GES.TIPO AS CODIGO_TIPO,
        CASE GES.TIPO
            WHEN 1 THEN 'GESTIONES'
            ELSE 'CARGAS' END AS DES_TIP_VC,
        'PREDICTIVO' AS DES_TIP_DET_VC,
        GES.ID_GEST_CALL_BI AS CODIGO,
        GES.ID_CONF_BI AS ID_CONFIGURACION,
        CONF.DES_CON_VC AS NOMBRE_CONFIGURACION,
        CLI.NRO_DOC_VC AS DOCUMENTO,
        CLI.NOM_COMP_VC AS NOMBRE_COMPLETO,
        CUE.NRO_CTA_VC AS NUMERO_CUENTA,
        CDA.DES_PROD_VC,
        CDA.DES_GRUP_VC,
        CDA.DES_SEGM_VC,
        CDA.DES_ESTR_VC,
        PRO.NOM_PROV_VC AS PROVEEDOR,
        CAR.NOM_CART_VC AS CARTERA,
        SCA.NOM_SUB_CART_VC AS SUBCARTERA,
        CONVERT(DATE,GES.FEC_GEST_DT) AS FECHA_GESTION,
        CONVERT(TIME, GES.FEC_GEST_DT) HORA_GESTION,
        CASE WHEN GES.TIPO=1 THEN TEL.DES_TEL_VC ELSE ISNULL(TEL.DES_TEL_VC,GES.DES_TEL_VC) END AS TELEFONO,
        TGE.DES_TIP_GES_VC AS TIPO_GESTION,
        CASE
            CASE WHEN TSO.ID_TIP_RES_SI>0 THEN TSO.CAL_TIP_RES_SI
            ELSE TRE.CAL_TIP_RES_SI END
        WHEN 1 THEN 'CONTACTO DIRECTO'
        WHEN 2 THEN 'CONTACTO INDIRECTO'
        WHEN 3 THEN 'NO CONTACTO' END AS TIPO_CONTACTO,
        TRE.DES_TIP_RES_VC AS TIPO_RESULTADO,
        TSO.DES_TIP_RES_VC AS TIPO_SOLUCION,
        CONVERT(DATE,GES.FEC_AGE_CITA_DT) AS FECHA_CITA,
        CONVERT(TIME,GES.FEC_AGE_CITA_DT) AS HORA_CITA,
        CONVERT(DATE,GES.FEC_RE_LLAM_DT) AS FECHA_RELLAMADA,
        CONVERT(TIME,GES.FEC_RE_LLAM_DT) AS HORA_RELLAMADA,
        CONVERT(TIME,GES.HOR_UBI_VC, 100) AS HORARIO_UBICACION,
        ISNULL(GES.MTO_CANC_DO,0) AS MONTO_CANCELACION,
        CONVERT(DATE,GES.FEC_CANC_DT) AS FECHA_CANCELACION,
        GES.NRO_AGENC_VC AS NUMERO_AGENCIA,
        CONVERT(DATE,GES.FEC_COMPR_DT) AS FECHA_COMPROMISO,
        ISNULL(GES.IMP_COMPR_DO,0) AS IMPORTE_COMPROMISO,
        CONVERT(DATE,GES.FEC_OPOR_DT) AS FECHA_OPORTUNIDAD,
        ISNULL(GES.IMP_OPOR_DO,0) AS IMPORTE_OPORTUNIDAD,
        ISNULL(GES.VAL_CUOT_INI_DO,0) AS VALOR_CUOTA_INICIAL,
        CONVERT(DATE,GES.FEC_CUOT_INI_DT) AS FECHA_CUOTA_INICIAL,
        ISNULL(GES.VAL_CUOT_MEN_DO,0) AS VALOR_CUOTA_MENSUAL,
        ISNULL(GES.NRO_CUOT_SI,0) AS NUMERO_CUOTAS,
        GES.TEX_OBS_VC AS OBSERVACION,
        ISNULL(GES.MON_CAPI_DO,0) AS MONTO_CAPITAL,
        ISNULL(GES.MON_DEUD_TOT_DO,0) AS MONTO_DEUDA_TOTAL,
        CASE WHEN GES.TIPO=1 THEN UAS.LOG_USU_VC ELSE GES.ASE_CALL_VC END AS ASESOR_ASIGNADO,
        CASE WHEN GES.TIPO=1 THEN UGE.LOG_USU_VC ELSE GES.ASE_CALL_VC END AS ASESOR_GESTIONA,
        USUP.LOG_USU_VC AS SUPERVISOR_ASIGNADO,
        STA.DES_STA_CLI_VC AS STATUS,
        CON.DESC_COND_VC AS CONDICION,
        CASE WHEN CLI.FLG_RET_PRO_BO=0 THEN 'ACTIVO' ELSE 'RETIRADO' END AS ESTADO_CLIENTE,
        CASE WHEN TSO.ID_TIP_RES_SI>0 THEN TSO.PES_TIP_RES_SI ELSE TRE.PES_TIP_RES_SI END AS PESO_RESULTADO
        FROM (
            SELECT 2 AS TIPO, TX.ID_GEST_CALL_BI, GCC.ID_CTA_BI,
            TX.ID_TIP_GES_SI,TX.FEC_GEST_DT,NULL FEC_AGE_CITA_DT,NULL HOR_AGE_CITA_VC,
            NULL FEC_RE_LLAM_DT,NULL HOR_RE_LLAM_VC,NULL HOR_UBI_VC,
            0 AS MTO_CANC_DO,NULL FEC_CANC_DT,NULL NRO_AGENC_VC,TX.FEC_COMPR_DT,TX.IMP_COMPR_DO,
            NULL FEC_OPOR_DT,0 AS IMP_OPOR_DO,0 AS VAL_CUOT_INI_DO,NULL FEC_CUOT_INI_DT,
            0 AS VAL_CUOT_MEN_DO,0 AS NRO_CUOT_SI,TX.TEX_OBS_VC,TX.DES_TEL_VC,
            TX.ID_TEL_BI,TX.ID_CLIE_BI,TX.ID_TIP_RES_SI,TX.ID_TIP_SOL_SI,NULL AS ASE_CALL_VC,
            TX.ID_ASE_CALL_BI,1 AS ID_ASE_ASI_SI,TX.ID_SUPER_ASI_SI,
            GCC.MON_CAPI_DO,GCC.MON_DEUD_TOT_DO,
            GCC.ID_SUB_CART_SI,1 AS ID_CAN_LLA_SI,
            TX.ID_CONF_BI
            FROM BD_MCOB.CALL.TBL_GESTION_VARIOS TX
            LEFT JOIN BD_MCOB.CALL.TBL_GESTION_VARIOS_CUENTAS GCC ON GCC.ID_GEST_CALL_BI=TX.ID_GEST_CALL_BI
            WHERE TX.FLG_EST_BO=1
              AND TX.FEC_GEST_DT >= @FECHA_INICIO
              AND TX.FEC_GEST_DT <  @FECHA_FIN
        ) GES
        LEFT JOIN BD_MCOB.CARGA.TBL_TELEFONO TEL ON TEL.ID_TEL_BI=GES.ID_TEL_BI
        INNER JOIN BD_MCOB.CARGA.TBL_CLIENTE CLI ON CLI.ID_CLIE_BI=GES.ID_CLIE_BI
        LEFT JOIN BD_MCOB.CARGA.TBL_CLIENTE_DATOS_ADICIONALES CLDA ON CLDA.NRO_DOC_VC=CLI.NRO_DOC_VC
        LEFT JOIN BD_MCOB.CARGA.TRF_TIPO_CONDICION CON ON CON.ID_TIP_CON_SI=CLDA.ID_TIP_CON_SI
        LEFT JOIN BD_MCOB.CARGA.TRF_STATUS_CLIENTE STA ON STA.ID_STA_CLI_SI=CLI.ID_STA_CLI_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_CUENTA CUE ON CUE.ID_CTA_BI=GES.ID_CTA_BI
        LEFT JOIN BD_MCOB.CARGA.TBL_CUENTA_DATOS_ADICIONALES CDA ON CDA.ID_CTA_BI=CUE.ID_CTA_BI
        INNER JOIN BD_MCOB.CALL.TBL_TIPO_GESTION TGE ON TGE.ID_TIP_GES_SI=GES.ID_TIP_GES_SI
        INNER JOIN BD_MCOB.CALL.TBL_TIPO_RESULTADO TRE ON TRE.ID_TIP_RES_SI=GES.ID_TIP_RES_SI
        LEFT JOIN BD_MCOB.CALL.TBL_TIPO_RESULTADO TSO ON TSO.ID_TIP_RES_SI=GES.ID_TIP_SOL_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_SUB_CARTERA SCA ON SCA.ID_SUB_CART_SI=GES.ID_SUB_CART_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_CARTERA CAR ON CAR.ID_CART_SI=SCA.ID_CART_SI
        LEFT JOIN BD_MCOB.CARGA.TBL_PROVEEDOR PRO ON PRO.ID_PROV_SI=CAR.ID_PROV_SI
        LEFT JOIN BD_MSEG.DBO.TBL_USUARIO UAS ON UAS.ID_USU_IN=GES.ID_ASE_ASI_SI
        LEFT JOIN BD_MSEG.DBO.TBL_USUARIO UGE ON UGE.ID_USU_IN=GES.ID_ASE_CALL_BI
        LEFT JOIN BD_MCOB.ADMINISTRACION.TBL_ASIG_CART_SUPERV ASI ON ASI.ID_SUB_CART_BI=GES.ID_SUB_CART_SI
            AND ASI.FLG_EST_BO=1
            AND ASI.FLG_ACT_BO=1
        LEFT JOIN BD_MSEG.DBO.TBL_USUARIO USUP ON USUP.ID_USU_IN=ASI.ID_SUPER_SI
        LEFT JOIN BD_MCOB.CONFIGURACION.TBL_CONFIGURACION CONF ON CONF.ID_CONF_BI=GES.ID_CONF_BI;

        SET @FILAS_STG = @@ROWCOUNT;

        /* ===================================================================
           PASO 2 — Intercambio del rango en destino (transacción corta)
           =================================================================== */
        BEGIN TRANSACTION;

            DELETE FROM REPORTE.TBL_GESTIONES
            WHERE FECHA_GESTION >= @FECHA_INICIO
              AND FECHA_GESTION <  @FECHA_FIN;
            SET @FILAS_DEL = @@ROWCOUNT;

            INSERT INTO REPORTE.TBL_GESTIONES
            (
                CODIGO_TIPO, DES_TIP_VC, DES_TIP_DET_VC, CODIGO, ID_CONFIGURACION,
                NOMBRE_CONFIGURACION, DOCUMENTO, NOMBRE_COMPLETO, NUMERO_CUENTA,
                DES_PROD_VC, DES_GRUP_VC, DES_SEGM_VC, DES_ESTR_VC, PROVEEDOR,
                CARTERA, SUBCARTERA, FECHA_GESTION, HORA_GESTION, TELEFONO,
                TIPO_GESTION, TIPO_CONTACTO, TIPO_RESULTADO, TIPO_SOLUCION,
                FECHA_CITA, HORA_CITA, FECHA_RELLAMADA, HORA_RELLAMADA,
                HORARIO_UBICACION, MONTO_CANCELACION, FECHA_CANCELACION,
                NUMERO_AGENCIA, FECHA_COMPROMISO, IMPORTE_COMPROMISO,
                FECHA_OPORTUNIDAD, IMPORTE_OPORTUNIDAD, VALOR_CUOTA_INICIAL,
                FECHA_CUOTA_INICIAL, VALOR_CUOTA_MENSUAL, NUMERO_CUOTAS,
                OBSERVACION, MONTO_CAPITAL, MONTO_DEUDA_TOTAL, ASESOR_ASIGNADO,
                ASESOR_GESTIONA, SUPERVISOR_ASIGNADO, STATUS, CONDICION,
                ESTADO_CLIENTE, PESO_RESULTADO
            )
            SELECT
                CODIGO_TIPO, DES_TIP_VC, DES_TIP_DET_VC, CODIGO, ID_CONFIGURACION,
                NOMBRE_CONFIGURACION, DOCUMENTO, NOMBRE_COMPLETO, NUMERO_CUENTA,
                DES_PROD_VC, DES_GRUP_VC, DES_SEGM_VC, DES_ESTR_VC, PROVEEDOR,
                CARTERA, SUBCARTERA, FECHA_GESTION, HORA_GESTION, TELEFONO,
                TIPO_GESTION, TIPO_CONTACTO, TIPO_RESULTADO, TIPO_SOLUCION,
                FECHA_CITA, HORA_CITA, FECHA_RELLAMADA, HORA_RELLAMADA,
                HORARIO_UBICACION, MONTO_CANCELACION, FECHA_CANCELACION,
                NUMERO_AGENCIA, FECHA_COMPROMISO, IMPORTE_COMPROMISO,
                FECHA_OPORTUNIDAD, IMPORTE_OPORTUNIDAD, VALOR_CUOTA_INICIAL,
                FECHA_CUOTA_INICIAL, VALOR_CUOTA_MENSUAL, NUMERO_CUOTAS,
                OBSERVACION, MONTO_CAPITAL, MONTO_DEUDA_TOTAL, ASESOR_ASIGNADO,
                ASESOR_GESTIONA, SUPERVISOR_ASIGNADO, STATUS, CONDICION,
                ESTADO_CLIENTE, PESO_RESULTADO
            FROM STG.TBL_GESTIONES_STG;
            SET @FILAS_INS = @@ROWCOUNT;

        COMMIT TRANSACTION;

        /* ---- Log: éxito ---- */
        UPDATE ETL.TBL_PROCESO_LOG
        SET ESTADO           = 'OK',
            FEC_FIN_DT       = SYSDATETIME(),
            DURACION_SEG     = DATEDIFF(SECOND, @INI_DT, SYSDATETIME()),
            FILAS_ELIMINADAS = @FILAS_DEL,
            FILAS_INSERTADAS = @FILAS_INS,
            MENSAJE          = CONCAT('STG=', @FILAS_STG, ' DEL=', @FILAS_DEL, ' INS=', @FILAS_INS)
        WHERE ID_LOG = @ID_LOG;
    END TRY
    BEGIN CATCH
        IF @@TRANCOUNT > 0
            ROLLBACK TRANSACTION;

        UPDATE ETL.TBL_PROCESO_LOG
        SET ESTADO       = 'ERROR',
            FEC_FIN_DT   = SYSDATETIME(),
            DURACION_SEG = DATEDIFF(SECOND, @INI_DT, SYSDATETIME()),
            MENSAJE      = CONCAT('ERROR ', ERROR_NUMBER(), ' (línea ', ERROR_LINE(), '): ', ERROR_MESSAGE())
        WHERE ID_LOG = @ID_LOG;

        THROW;  -- propaga el error al llamador (Node / Agent) para que falle visible
    END CATCH
END
GO
